import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mockBackend } from './fixtures';

test('new tab opens the exact current location without a picker, and menus stay in that tab', async ({ page }) => {
  await mockBackend(page); await page.goto('/#/files?dir=docs');
  await expect(page.getByRole('button', { name: 'Archive notes.md' })).toBeVisible();
  const source = page.url();
  await page.getByRole('button', { name: 'Open a new tab' }).click();
  await expect(page.getByRole('tab')).toHaveCount(2);
  expect(page.url()).toBe(source);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Archive notes.md' })).toBeVisible();
  await page.getByRole('link', { name: 'Tools', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tools', exact: true })).toBeVisible();
  await expect(page.getByRole('tab')).toHaveCount(2);
  await page.getByRole('tab', { name: 'Tools', exact: true }).press('ArrowLeft');
  await expect(page.getByRole('tab', { name: 'Files', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('button', { name: 'Archive notes.md' })).toBeVisible();
});

test('split shows two independent panes, preserves live chat, resizes and joins without losing state', async ({ page }) => {
  const backend = await mockBackend(page);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('/#/chat?session=1&conversation=1');
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Left draft');
  const originalSocket = backend.sockets.find(socket => socket.url.includes('/conversations/1') && !socket.closed)!;
  await page.getByRole('button', { name: 'Split view', exact: true }).click();
  await expect(page.locator('main:not([hidden])')).toHaveCount(2);
  await expect(page.getByRole('tab')).toHaveCount(2);
  await page.getByRole('link', { name: 'Files', exact: true }).click();
  const left = page.locator('main:not([hidden])').first(); const right = page.locator('main:not([hidden])').last();
  await expect(left.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('Left draft');
  await expect(right.getByRole('button', { name: 'README.md' })).toBeVisible();
  await right.getByRole('searchbox', { name: 'Search this folder' }).fill('README');
  await left.getByRole('textbox', { name: 'Message', exact: true }).click();
  await page.getByRole('link', { name: 'Tools', exact: true }).click();
  await expect(left.getByRole('heading', { name: 'Tools', exact: true })).toBeVisible();
  await expect(right.getByRole('searchbox', { name: 'Search this folder' })).toHaveValue('README');
  await page.getByRole('link', { name: 'Chat', exact: true }).click();
  await expect(left.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('Left draft');
  expect(originalSocket.closed).toBe(false);
  const divider = page.getByRole('separator', { name: 'Resize panes' });
  const handle = (await divider.boundingBox())!;
  await page.mouse.move(handle.x + handle.width / 2, handle.y + 80);
  await page.mouse.down(); await page.mouse.move(handle.x + 100, handle.y + 80); await page.mouse.up();
  expect(Number(await divider.getAttribute('aria-valuenow'))).toBeGreaterThan(55);
  await divider.dblclick(); await expect(divider).toHaveAttribute('aria-valuenow', '50');
  await divider.press('ArrowRight'); await expect(divider).toHaveAttribute('aria-valuenow', '52');
  await divider.dblclick(); await expect(divider).toHaveAttribute('aria-valuenow', '50');
  await page.screenshot({ path: '../web_design/qa-split-1440.png' });
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze();
  expect(audit.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.target) }))).toEqual([]);
  await page.getByRole('button', { name: 'Close split view' }).click();
  await expect(page.locator('main:not([hidden])')).toHaveCount(1);
  await expect(page.getByRole('tab')).toHaveCount(2);
  await page.getByRole('tab', { name: 'Files', exact: true }).click();
  await expect(page.getByRole('searchbox', { name: 'Search this folder' })).toHaveValue('README');
  await page.reload();
  await expect(page.getByRole('tab')).toHaveCount(2);
  await page.getByRole('button', { name: 'Split view', exact: true }).click();
  await divider.press('ArrowLeft'); await expect(divider).toHaveAttribute('aria-valuenow', '48');
  await expect(page.getByRole('tab')).toHaveCount(2);
  await page.reload();
  await expect(page.locator('main:not([hidden])')).toHaveCount(2);
  await expect(divider).toHaveAttribute('aria-valuenow', '48');
  await page.setViewportSize({ width: 390, height: 900 });
  await expect(divider).toHaveAttribute('aria-orientation', 'horizontal');
  await divider.press('ArrowDown'); await expect(divider).toHaveAttribute('aria-valuenow', '50');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
